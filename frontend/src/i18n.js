const interpolate = (value, replacements = {}) => {
  return Object.entries(replacements).reduce(
    (text, [name, replacement]) =>
      text.replace(new RegExp(`\\{${name}\\}`, "g"), replacement),
    value
  );
};

export const translate = (language, key, fallback = "", replacements = {}) => {
  const value = nestedGet(translations[language] || translations.en, key);
  const resolved = value !== undefined ? value : nestedGet(translations.en, key) ?? fallback ?? key;
  return typeof resolved === "string" ? interpolate(resolved, replacements) : resolved;
};
